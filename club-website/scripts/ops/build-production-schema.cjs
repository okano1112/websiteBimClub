// Generate a clean bootstrap for a NEW database only. Existing databases use reviewed migrations.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = name => fs.readFileSync(path.join(root, 'database', name), 'utf8');
const statements = read('schema.sql')
  .split('\n').filter(line => !line.trimStart().startsWith('--')).join('\n')
  .split(';').map(part => part.trim()).filter(Boolean)
  .filter(part => /^(?:CREATE TABLE|ALTER TABLE)/i.test(part));
const projects = read('controlled-p04-project-collaborators.sql')
  .split('DROP PROCEDURE')[0]
  .split('\n').filter(line => !line.trimStart().startsWith('--')).join('\n')
  .split(';').map(part => part.trim()).filter(part => /^CREATE TABLE/i.test(part));
const sessions = read('migrations/001-production-sessions.sql').trim().replace(/;\s*$/, '');
const sql = '-- Generated by scripts/ops/build-production-schema.cjs. NEW EMPTY DATABASE ONLY.\n' +
  '-- Contains no sample users, sample content, DROP statements, or credentials.\n\n' + [
  ...statements,
  'ALTER TABLE activities ADD COLUMN start_date DATE DEFAULT NULL',
  'ALTER TABLE activities ADD COLUMN end_date DATE DEFAULT NULL',
  ...projects,
  sessions,
  read('migrations/003-auth-rate-limits.sql').trim().replace(/;\s*$/, '')
].join(';\n\n') + ';\n';
if ([...statements, ...projects, sessions].some(part => /^(?:DROP|INSERT|DELETE|UPDATE|TRUNCATE)\b/i.test(part))) throw Error('Unsafe production bootstrap statement');
fs.writeFileSync(path.join(root, 'database', 'schema.production.sql'), sql);
